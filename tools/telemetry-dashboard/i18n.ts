const DICTS: Record<Locale, Record<string, string>> = { en, zh, de, fr };

let current: Locale = detect();
const listeners: (() => void)[] = [];

function isLocale(value: string | null): value is Locale {
  return value !== null && (LOCALES as string[]).includes(value);
}

function detect(): Locale {
  const query = new URLSearchParams(location.search).get("lang");
  if (isLocale(query)) return query;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isLocale(saved)) return saved;
  } catch {
    // Storage can be unavailable (private mode); fall through to navigator.
  }
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("fr")) return "fr";
  return "en";
}

/** Translate `key`; `{name}` placeholders are filled from `vars`. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const template = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function getLocale(): Locale {
  return current;
}

/** Switch language, persist it, and notify listeners (the panels re-render). */
export function setLocale(locale: Locale): void {
  if (locale === current) return;
  current = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // Preference is best-effort.
  }
  applyStaticTranslations();
  for (const listener of listeners) listener();
}

export function onLocaleChange(listener: () => void): void {
  listeners.push(listener);
}

/** Apply `data-i18n` / `data-i18n-title` / `<title>` / `<html lang>`. */
export function applyStaticTranslations(): void {
  document.documentElement.lang = LANG_TAG[current];
  document.title = t("title");
  for (const el of document.querySelectorAll<HTMLElement>("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n ?? "");
  }
  for (const el of document.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle ?? "");
  }
}

/** Mark the active button of the language switcher. */
export function syncSwitcher(): void {
  for (const button of document.querySelectorAll<HTMLElement>("#lang [data-locale]")) {
    button.classList.toggle("active", button.dataset.locale === current);
  }
}
